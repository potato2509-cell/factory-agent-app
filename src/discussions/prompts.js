/**
 * 특정 페르소나의 완성된 system prompt 생성
 * @param {string} code - 'PE' | 'ME' | 'TE' | 'FA' | 'VISION'
 * @param {string} learningContext - 학습 데이터 (선택)
 * @returns {string} 완성된 system prompt
 */
export function buildPersonaSystemPrompt(code, learningContext = '') {
  const persona = PERSONAS[code];
  if (!persona) throw new Error(`Unknown persona code: ${code}`);

  return [
    FACTORY_PHILOSOPHY,
    persona.prompt,
    learningContext ? `[학습 데이터]\n${learningContext}` : '',
    OUTPUT_RULES,
  ].filter(Boolean).join('\n\n');
}

// ===========================================================================
// 페르소나 USER 메시지 빌더 (순차 호출 시 이전 의견 누적)
// ===========================================================================
/**
 * @param {string} userQuestion - 원 질문/이슈 본문
 * @param {Array<{persona:string, opinion:string}>} previousOpinions - 이전 발언자 의견들
 * @returns {string}
 */
export function buildPersonaUserMessage(userQuestion, previousOpinions = []) {
  const parts = [`[이슈 / 질문]\n${userQuestion}`];

  if (previousOpinions.length > 0) {
    const prev = previousOpinions
      .map(o => `── ${o.persona} 의견 ──\n${o.opinion}`)
      .join('\n\n');
    parts.push(`[먼저 발언한 동료 의견]\n${prev}`);
    parts.push(
      `위 의견들을 참고하여 당신의 관점에서 의견을 제시하십시오.\n` +
      `동의할 부분은 짧게 동의 표시, 다른 입장일 때만 명확히 다른 관점을 제시하십시오.`
    );
  } else {
    parts.push(`당신의 관점에서 분석 의견을 제시하십시오.`);
  }

  return parts.join('\n\n');
}

